-- Registrar governance, tutor assignment, and in-class-only teaching materials.
-- Review scheduled_classes/profiles column names against the deployed schema before applying.

create table if not exists public.class_materials (
  id uuid primary key default gen_random_uuid(),
  class_id uuid not null references public.scheduled_classes(id) on delete cascade,
  uploaded_by uuid not null references auth.users(id),
  title text not null,
  material_type text not null check (material_type in ('note','audio','video')),
  storage_path text not null unique,
  is_hidden boolean not null default false,
  created_at timestamptz not null default now(),
  hidden_at timestamptz,
  deleted_at timestamptz,
  deleted_by uuid references auth.users(id)
);

alter table public.class_materials enable row level security;

create or replace function public.is_school_registrar()
returns boolean language sql stable security definer set search_path=public,auth as $$
  select exists(select 1 from public.registrars r where r.user_id=auth.uid())
    or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('registrar','admin'));
$$;

create or replace function public.class_session_is_live(p_class_id uuid)
returns boolean language sql stable security definer set search_path=public,auth as $$
  select exists (
    select 1 from public.scheduled_classes c
    where c.id=p_class_id
      and now() >= c.starts_at - interval '15 minutes'
      and now() <= c.starts_at + make_interval(mins => coalesce(c.duration_minutes,60)) + interval '15 minutes'
      and coalesce(c.status,'scheduled') not in ('cancelled','deleted')
  );
$$;

create or replace function public.registrar_assign_tutor(p_class_id uuid, p_tutor_id uuid)
returns boolean language plpgsql security definer set search_path=public,auth as $$
begin
  if not public.is_school_registrar() then raise exception 'Registrar access required'; end if;
  if not exists(select 1 from public.profiles p where p.id=p_tutor_id and p.role in ('tutor','teacher')) then
    raise exception 'Tutor must be approved before assignment';
  end if;
  update public.scheduled_classes set teacher_id=p_tutor_id where id=p_class_id;
  if not found then raise exception 'Class not found'; end if;
  return true;
end; $$;

create or replace function public.registrar_class_assignment_options()
returns table(class_id uuid, class_title text, class_level text, starts_at timestamptz, tutor_id uuid, tutor_name text)
language plpgsql security definer set search_path=public,auth as $$
begin
  if not public.is_school_registrar() then raise exception 'Registrar access required'; end if;
  return query select c.id,c.title,c.level,c.starts_at,c.teacher_id,p.full_name
    from public.scheduled_classes c left join public.profiles p on p.id=c.teacher_id
    order by c.starts_at desc;
end; $$;

create or replace function public.registrar_approved_tutors()
returns table(tutor_id uuid, tutor_name text, tutor_email text)
language plpgsql security definer set search_path=public,auth as $$
begin
  if not public.is_school_registrar() then raise exception 'Registrar access required'; end if;
  return query select p.id,coalesce(p.full_name,'Tutor'),u.email
    from public.profiles p join auth.users u on u.id=p.id
    where p.role in ('tutor','teacher') order by p.full_name;
end; $$;

-- Only active class participants can read non-hidden materials; signed URLs are generated by the private bucket.
drop policy if exists class_materials_read_in_live_class on public.class_materials;
create policy class_materials_read_in_live_class on public.class_materials for select to authenticated
using (
  deleted_at is null and (
    public.is_school_registrar()
    or exists(select 1 from public.scheduled_classes c where c.id=class_id and c.teacher_id=auth.uid())
    or (public.class_session_is_live(class_id) and not is_hidden and exists(
      select 1 from public.profiles p join public.scheduled_classes c on c.id=class_id
      where p.id=auth.uid() and p.role not in ('tutor','teacher','registrar','admin')
        and coalesce(p.access_approved,false)=true
        and (p.access_expires_at is null or p.access_expires_at > now())
        and (to_jsonb(p)->>'level' = c.level or to_jsonb(p)->>'course_level' = c.level)
    ))
  )
);

drop policy if exists class_materials_tutor_upload_assigned_class on public.class_materials;
create policy class_materials_tutor_upload_assigned_class on public.class_materials for insert to authenticated
with check (
  uploaded_by=auth.uid() and exists(select 1 from public.scheduled_classes c where c.id=class_id and c.teacher_id=auth.uid())
  and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('tutor','teacher'))
);

drop policy if exists class_materials_tutor_hide_assigned on public.class_materials;
create policy class_materials_tutor_hide_assigned on public.class_materials for update to authenticated
using (exists(select 1 from public.scheduled_classes c where c.id=class_id and c.teacher_id=auth.uid()) and uploaded_by=auth.uid() and deleted_at is null)
with check (exists(select 1 from public.scheduled_classes c where c.id=class_id and c.teacher_id=auth.uid()) and uploaded_by=auth.uid() and deleted_at is null);

drop policy if exists class_materials_registrar_delete on public.class_materials;
create policy class_materials_registrar_delete on public.class_materials for delete to authenticated using (public.is_school_registrar());

-- A private bucket prevents public URL access. Storage object path format: <class_uuid>/<random-file-name>.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('class-materials','class-materials',false,52428800,
  array['application/pdf','text/plain','audio/mpeg','audio/mp4','audio/wav','audio/ogg','video/mp4','video/webm','video/quicktime'])
on conflict (id) do update set public=false, file_size_limit=52428800;

drop policy if exists class_material_storage_upload_assigned on storage.objects;
create policy class_material_storage_upload_assigned on storage.objects for insert to authenticated
with check (bucket_id='class-materials' and exists(
  select 1 from public.scheduled_classes c join public.profiles p on p.id=auth.uid()
  where c.id=(split_part(name,'/',1))::uuid and c.teacher_id=auth.uid() and p.role in ('tutor','teacher')
));

drop policy if exists class_material_storage_read_live on storage.objects;
create policy class_material_storage_read_live on storage.objects for select to authenticated
using (bucket_id='class-materials' and exists(
  select 1 from public.class_materials m where m.storage_path=name and m.deleted_at is null and (
    public.is_school_registrar()
    or exists(select 1 from public.scheduled_classes c where c.id=m.class_id and c.teacher_id=auth.uid())
    or (public.class_session_is_live(m.class_id) and not m.is_hidden and exists(
      select 1 from public.profiles p join public.scheduled_classes c on c.id=m.class_id
      where c.id=m.class_id and p.id=auth.uid() and p.role not in ('tutor','teacher','registrar','admin')
        and coalesce(p.access_approved,false)=true and (p.access_expires_at is null or p.access_expires_at>now())
        and (to_jsonb(p)->>'level'=c.level or to_jsonb(p)->>'course_level'=c.level)
    ))
  )
));

drop policy if exists class_material_storage_registrar_delete on storage.objects;
create policy class_material_storage_registrar_delete on storage.objects for delete to authenticated
using (bucket_id='class-materials' and public.is_school_registrar());

revoke all on function public.registrar_assign_tutor(uuid,uuid) from public,anon;
revoke all on function public.registrar_class_assignment_options() from public,anon;
revoke all on function public.registrar_approved_tutors() from public,anon;
grant execute on function public.registrar_assign_tutor(uuid,uuid) to authenticated;
grant execute on function public.registrar_class_assignment_options() to authenticated;
grant execute on function public.registrar_approved_tutors() to authenticated;
revoke update on public.class_materials from authenticated;
grant select,insert,delete on public.class_materials to authenticated;
grant update (is_hidden, hidden_at) on public.class_materials to authenticated;
